test("only a sales officer is limited to assigned farmers", () => {
  assert.equal(fieldOfficerSeesOwnFarmers("sales_officer"), true);
  assert.equal(fieldOfficerSeesOwnFarmers("admin"), false);
  assert.equal(fieldOfficerSeesOwnFarmers("regional_manager"), false);
  assert.equal(fieldOfficerSeesOwnFarmers("store_manager"), false);
  assert.equal(fieldOfficerSeesOwnFarmers(null), false);
});

test("every sheet officer name matches one field officer", () => {
  const byId = new Map(officers.map((officer) => [officer.id, officer.name]));
  const missed: string[] = [];
  for (const raw of sheetNames) {
    const id = matchOfficerId(raw, officers);
    if (!id) missed.push(raw);
    else if (expected[raw] && byId.get(id) !== expected[raw]) {
      missed.push(`${raw} -> ${byId.get(id)} wanted ${expected[raw]}`);
    }
  }
  assert.deepEqual(missed, []);
  assert.equal(matchOfficerId("", officers), null);
  assert.equal(matchOfficerId("   ", officers), null);
});
